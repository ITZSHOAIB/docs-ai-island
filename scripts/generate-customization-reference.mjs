import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { partContract, themeTokenContract } from "../src/customization-contract.ts";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = resolve(root, "docs/reference/customization.md");
const runtimeOutputPath = resolve(root, "src/generated/customization-contract.ts");
const tokenCssPath = resolve(root, "src/styles/tokens.css");
const cssPaths = ["tokens.css", "structure.css", "components.css", "states.css"].map((file) =>
  resolve(root, "src/styles", file),
);

function normalizeCssValue(value) {
  return value.replace(/\s+/g, " ").trim();
}

function sorted(values) {
  return [...values].sort((left, right) => left.localeCompare(right));
}

function difference(left, right) {
  return sorted(left).filter((value) => !right.has(value));
}

function assertEqualSet(actual, expected, label) {
  const missing = difference(expected, actual);
  const unexpected = difference(actual, expected);
  if (missing.length === 0 && unexpected.length === 0) return;

  const details = [
    missing.length === 0 ? undefined : `missing: ${missing.join(", ")}`,
    unexpected.length === 0 ? undefined : `unexpected: ${unexpected.join(", ")}`,
  ].filter(Boolean);
  throw new Error(`${label} does not match the customization contract (${details.join("; ")})`);
}

async function validateTokenCss() {
  const tokenCss = await readFile(tokenCssPath, "utf8");
  const defaultBlock = tokenCss.match(/:where\(\[data-docs-ai-island\]\)\s*\{(?<body>[\s\S]*?)\n\}/)
    ?.groups?.body;
  if (!defaultBlock) throw new Error("Could not find the default Island token block");

  const declarations = new Map(
    [...defaultBlock.matchAll(/^\s*(--docs-ai-island-[\w-]+):\s*(.+);\s*$/gm)].map(
      ([, property, value]) => [property, normalizeCssValue(value)],
    ),
  );
  const contractProperties = new Set(
    Object.values(themeTokenContract).map((token) => token.property),
  );
  assertEqualSet(new Set(declarations.keys()), contractProperties, "Default CSS tokens");

  for (const token of Object.values(themeTokenContract)) {
    const actual = declarations.get(token.property);
    const expected = normalizeCssValue(token.defaultValue);
    if (actual !== expected) {
      throw new Error(
        `${token.property} default is ${JSON.stringify(actual)}; expected ${JSON.stringify(expected)}`,
      );
    }
  }

  const usedProperties = new Set();
  const styledParts = new Set();
  for (const path of cssPaths) {
    const css = await readFile(path, "utf8");
    for (const [property] of css.matchAll(/--docs-ai-island-[\w-]+/g)) usedProperties.add(property);
    for (const [, part] of css.matchAll(/data-part="([^"]+)"/g)) styledParts.add(part);
  }
  assertEqualSet(usedProperties, contractProperties, "Prefixed CSS properties");
  assertEqualSet(
    styledParts,
    new Set(Object.values(partContract).map((part) => part.name)),
    "Styled DOM parts",
  );
}

function renderTokenTable() {
  const rows = Object.entries(themeTokenContract).map(
    ([name, token]) =>
      `| \`${name}\` | \`${token.property}\` | \`${token.defaultValue}\` | ${token.category} | ${token.description} |`,
  );
  return [
    "| Theme key | CSS property | Default | Category | Purpose |",
    "| --- | --- | --- | --- | --- |",
    ...rows,
  ].join("\n");
}

function renderPartTable() {
  const rows = Object.values(partContract)
    .toSorted((left, right) => left.name.localeCompare(right.name))
    .map(
      (part) => `| \`[data-part="${part.name}"]\` | \`<${part.element}>\` | ${part.description} |`,
    );
  return ["| Selector | Default element | Purpose |", "| --- | --- | --- |", ...rows].join("\n");
}

function renderReference() {
  return `<!-- This file is generated by pnpm docs:customization. Do not edit it directly. -->

# Customization reference

Docs AI Island exposes semantic configuration for common choices and a stable styling contract for precise visual control. Import the default stylesheet, then override tokens through the typed \`theme\` option or scoped CSS.

## Theme tokens

Every token works both as a key in \`config.theme\` and as a CSS custom property on \`[data-docs-ai-island]\`.

${renderTokenTable()}

### Typed configuration

\`\`\`ts
mountDocsAiIsland({
  theme: {
    accent: "var(--vp-c-brand-1)",
    menuRadius: "14px",
    itemHeight: "54px",
    backdropFilter: "blur(18px) saturate(125%)",
  },
})
\`\`\`

### CSS override

\`\`\`css
[data-docs-ai-island] {
  --docs-ai-island-accent: var(--sl-color-accent);
  --docs-ai-island-font-family: var(--sl-font);
  --docs-ai-island-offset-block: 32px;
}
\`\`\`

Runtime \`theme\` values are inline custom properties and therefore take precedence over ordinary author CSS. Prefer one method per token. Color-scheme and density variants intentionally replace some defaults; a runtime \`theme\` value still wins.

## Stable parts

Parts are stable styling hooks under the Island root. They are not global selectors: always scope overrides through \`[data-docs-ai-island]\`. Optional content, custom icons, group kinds, and Action configuration determine whether a particular part is rendered.

${renderPartTable()}

\`\`\`css
[data-docs-ai-island] [data-part="trigger"] {
  border-radius: 999px;
}

[data-docs-ai-island] [data-part="action-description"] {
  font-size: 0.8rem;
}
\`\`\`

The default element column describes the current built-in renderer. The \`data-part\` value is the compatibility contract; do not target internal structure, child order, or undocumented classes.
`;
}

function renderRuntimeContract() {
  const tokenProperties = Object.entries(themeTokenContract).map(
    ([name, token]) => `  ${name}: ${JSON.stringify(token.property)},`,
  );
  const partNames = Object.entries(partContract).map(
    ([key, part]) => `  ${key}: ${JSON.stringify(part.name)},`,
  );

  return `// Generated by pnpm docs:customization. Do not edit directly.

export const themeProperties = {
${tokenProperties.join("\n")}
} as const;

export type DocsAiIslandThemeTokenName = keyof typeof themeProperties;

export const parts = {
${partNames.join("\n")}
} as const;

export type DocsAiIslandPartName = (typeof parts)[keyof typeof parts];
`;
}

await validateTokenCss();
const output = renderReference();
const runtimeOutput = renderRuntimeContract();

if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => undefined);
  const currentRuntime = await readFile(runtimeOutputPath, "utf8").catch(() => undefined);
  if (current !== output || currentRuntime !== runtimeOutput) {
    throw new Error(
      "Generated customization files are stale. Run pnpm docs:customization and commit the result.",
    );
  }
  console.log("Customization reference is current and its token and part contracts match CSS.");
} else {
  await mkdir(dirname(outputPath), { recursive: true });
  await mkdir(dirname(runtimeOutputPath), { recursive: true });
  await writeFile(outputPath, output);
  await writeFile(runtimeOutputPath, runtimeOutput);
  console.log(`Generated ${outputPath} and ${runtimeOutputPath}`);
}
